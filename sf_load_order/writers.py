    lines = ["How to apply the recommended load order", "=======================================", ""]
    lines += list(intro or [])
    if same:
        lines += ["The files in this folder equal your current order: nothing moves, so there is nothing to apply.",
                  "They are written anyway, so you can keep them as a record of a checked order.", ""]
    if estimate:
        lines += ["Note: the recommended order's score is an estimate (the record-conflict data lists only the "
                  "current order's losses). Check the moved mods in game after applying it.", ""]
    if src == "vortex" and "vortex_json" not in files:
        lines += [f"You use Vortex, but {VORTEX_JSON} couldn't be written (the report's Rating findings say why), "
                  "so there is no file for Vortex's Import button this time.", "",
                  "Fix the cause and run sf-load-order again; until then keep your current order.", "",
                  "Don't copy plugins.txt into the game folder while you use Vortex: Vortex rewrites that file when "
                  "it deploys."]
